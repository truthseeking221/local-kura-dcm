// ── Public API ──────────────────────────────────────────────────────────────

function openPdf(builderFn, filename) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  builderFn(doc);
  const blob = doc.output("blob");
  const url = URL.createObjectURL(blob);
  // Open inline in a new tab. The browser's PDF viewer handles render + download.
  window.open(url, "_blank", "noopener,noreferrer");
  // Revoke after a delay so the browser has time to fetch.
  setTimeout(() => URL.revokeObjectURL(url), 60_000);
  return { url, filename };
}

export function openEcgPdf() {
  return openPdf(buildECG, "sokha-chann-ecg.pdf");
}

export function openChestXrayPdf() {
  return openPdf(buildChestXray, "sokha-chann-chest-xray.pdf");
}

export function openAbdominalUsPdf() {
  return openPdf(buildAbdominalUS, "sokha-chann-abdominal-us.pdf");
}

export function openDocumentPdf(kind) {
  if (kind === "ECG") return openEcgPdf();
  if (kind === "X-ray") return openChestXrayPdf();
  if (kind === "Ultrasound") return openAbdominalUsPdf();
  return null;
}
