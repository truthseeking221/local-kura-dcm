// ── 3. Abdominal ultrasound ─────────────────────────────────────────────────

function drawUSPanel(doc, x, y, w, h, { label, annotations = [] }) {
  // Black image area with fan-shaped probe outline
  doc.setFillColor(10, 10, 14);
  doc.rect(x, y, w, h, "F");

  // Faux ultrasound sweep — light grayscale specks
  doc.setDrawColor(220);
  doc.setLineWidth(0.2);
  for (let i = 0; i < 80; i += 1) {
    const px = x + 4 + Math.random() * (w - 8);
    const py = y + 4 + Math.random() * (h - 8);
    doc.line(px, py, px + 0.6, py + 0.6);
  }

  // Soft organ silhouette — irregular blob
  doc.setFillColor(70, 70, 75);
  doc.triangle(x + w * 0.25, y + h * 0.35, x + w * 0.7, y + h * 0.25, x + w * 0.5, y + h * 0.7, "F");
  doc.triangle(x + w * 0.25, y + h * 0.35, x + w * 0.5, y + h * 0.7, x + w * 0.15, y + h * 0.55, "F");
  doc.setFillColor(95, 95, 100);
  doc.triangle(x + w * 0.4, y + h * 0.45, x + w * 0.65, y + h * 0.4, x + w * 0.55, y + h * 0.6, "F");

  // Measurement markers (calipers)
  doc.setDrawColor(250, 230, 100);
  doc.setLineWidth(0.6);
  doc.line(x + w * 0.32, y + h * 0.4, x + w * 0.62, y + h * 0.55);
  doc.setFontSize(6.5);
  doc.setTextColor(250, 230, 100);
  doc.text("+", x + w * 0.31, y + h * 0.4 + 1);
  doc.text("+", x + w * 0.62, y + h * 0.55 + 1);

  // Border
  doc.setDrawColor(140);
  doc.setLineWidth(0.6);
  doc.rect(x, y, w, h, "S");

  // Label inside top-left
  doc.setFontSize(7.5);
  doc.setTextColor(240);
  doc.text(label, x + 6, y + 10);

  // Annotation strip below
  doc.setFontSize(7.5);
  doc.setTextColor(60);
  let ay = y + h + 10;
  for (const ann of annotations) {
    doc.text(ann, x, ay);
    ay += 10;
  }
}

