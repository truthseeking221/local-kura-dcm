// ── ECG waveform drawing ────────────────────────────────────────────────────

// A single PQRST cycle, parameterised. Returns array of [x,y] offsets.
function ecgWavePoints(opts = {}) {
  const { qrsAmp = 12, sAmp = 0, tAmp = 3, baseline = 0 } = opts;
  // Roughly: flat → small P → flat → big QRS → flat → T → flat
  const pts = [];
  const push = (x, y) => pts.push([x, baseline - y]);
  // baseline before P
  for (let x = 0; x < 8; x += 1) push(x, 0);
  // P wave (small bump)
  push(8, 0); push(10, 1.2); push(12, 1.6); push(14, 1.2); push(16, 0);
  // PR segment
  push(18, 0); push(20, 0); push(22, 0);
  // Q (small dip)
  push(23, -1);
  // R (tall spike up)
  push(24, qrsAmp);
  // S (sharp down)
  push(25, -sAmp);
  // back to baseline
  push(27, 0); push(29, 0);
  // T wave
  push(32, tAmp); push(35, tAmp * 1.4); push(38, tAmp); push(41, 0);
  // baseline to end
  for (let x = 43; x < 60; x += 2) push(x, 0);
  return pts;
}

function drawECGGrid(doc, x, y, w, h) {
  // 1mm small squares, 5mm large squares — pink/red
  const sm = 4; // pt per small square (visual approx)
  const lg = sm * 5;

  doc.setLineWidth(0.15);
  doc.setDrawColor(255, 200, 200);
  for (let gx = 0; gx <= w; gx += sm) doc.line(x + gx, y, x + gx, y + h);
  for (let gy = 0; gy <= h; gy += sm) doc.line(x, y + gy, x + w, y + gy);

  doc.setLineWidth(0.35);
  doc.setDrawColor(220, 100, 100);
  for (let gx = 0; gx <= w; gx += lg) doc.line(x + gx, y, x + gx, y + h);
  for (let gy = 0; gy <= h; gy += lg) doc.line(x, y + gy, x + w, y + gy);
}

function drawECGTrace(doc, x, y, label, opts) {
  const w = 130;
  const h = 60;
  drawECGGrid(doc, x, y, w, h);

  // Lead label
  doc.setFont("helvetica", "bold");
  doc.setFontSize(7);
  doc.setTextColor(60);
  doc.text(label, x + 3, y + 9);

  // Calibration mark (1mV step at start)
  doc.setDrawColor(20);
  doc.setLineWidth(0.7);
  const cy = y + h / 2;
  doc.line(x + 14, cy, x + 16, cy);
  doc.line(x + 16, cy, x + 16, cy - 10);
  doc.line(x + 16, cy - 10, x + 18, cy - 10);
  doc.line(x + 18, cy - 10, x + 18, cy);
  doc.line(x + 18, cy, x + 20, cy);

  // Three beats across the lead
  doc.setLineWidth(0.7);
  doc.setDrawColor(20);
  const cycleW = 36;
  const startX = x + 22;
  const pts = ecgWavePoints(opts);
  for (let beat = 0; beat < 3; beat += 1) {
    const ox = startX + beat * cycleW;
    let prev = null;
    for (const [px, py] of pts) {
      const cx = ox + (px / 60) * cycleW;
      const cyAdj = cy - py * 1.2;
      if (prev) doc.line(prev[0], prev[1], cx, cyAdj);
      prev = [cx, cyAdj];
    }
  }
}

