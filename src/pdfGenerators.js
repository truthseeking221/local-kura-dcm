// ── 2. Chest X-ray ──────────────────────────────────────────────────────────

function drawChestImage(doc, x, y, w, h) {
  // Black film background
  doc.setFillColor(15, 15, 18);
  doc.rect(x, y, w, h, "F");

  // Soft tissue / lung field gradient — approximated with darker rects
  const cx = x + w / 2;

  // Ribs (curved lines)
  doc.setDrawColor(220, 220, 215);
  doc.setLineWidth(0.5);
  for (let i = 0; i < 9; i += 1) {
    const ry = y + 28 + i * 16;
    // Left side rib
    doc.line(x + 24, ry, cx - 14, ry + 4);
    // Right side rib
    doc.line(cx + 14, ry + 4, x + w - 24, ry);
  }

  // Clavicles
  doc.setLineWidth(1.4);
  doc.setDrawColor(240);
  doc.line(x + 30, y + 30, cx - 10, y + 38);
  doc.line(cx + 10, y + 38, x + w - 30, y + 30);

  // Spine — vertical column of vertebrae
  doc.setLineWidth(2.2);
  doc.setDrawColor(180);
  doc.line(cx, y + 20, cx, y + h - 14);
  doc.setLineWidth(0.4);
  for (let i = 0; i < 12; i += 1) {
    doc.line(cx - 4, y + 26 + i * 12, cx + 4, y + 26 + i * 12);
  }

  // Heart silhouette (cardiac shadow, slightly to the left)
  doc.setFillColor(60, 60, 65);
  // Approx heart shape with two triangles
  doc.triangle(cx - 6, y + 90, cx - 60, y + 130, cx - 6, y + 180, "F");
  doc.triangle(cx - 6, y + 90, cx + 22, y + 110, cx + 22, y + 180, "F");
  doc.triangle(cx - 60, y + 180, cx + 22, y + 180, cx - 18, y + 200, "F");

  // Diaphragm — two curves
  doc.setFillColor(75, 75, 80);
  doc.triangle(x + 24, y + h - 60, cx - 4, y + h - 90, cx - 4, y + h - 50, "F");
  doc.triangle(cx + 4, y + h - 90, x + w - 24, y + h - 60, cx + 4, y + h - 50, "F");

  // Outer chest wall (rounded outline)
  doc.setDrawColor(200);
  doc.setLineWidth(1);
  doc.line(x + 20, y + 20, x + 20, y + h - 30);
  doc.line(x + w - 20, y + 20, x + w - 20, y + h - 30);
  doc.line(x + 20, y + h - 30, x + w - 20, y + h - 30);

  // Markers
  doc.setFontSize(10);
  doc.setTextColor(240);
  doc.text("R", x + 8, y + 16);
  doc.text("L", x + w - 14, y + 16);

  // PA marker
  doc.setFontSize(8);
  doc.setTextColor(180);
  doc.text("PA · upright · inspiration", x + 8, y + h - 8);
}

